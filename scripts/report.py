"""Generate each dataset's results.md from the result files it was read from.

The paper's tables are edited by hand and cut to what fits. These are not: they
are written from the JSON the cluster produced, so every column that was
measured appears, and a rerun updates them by running this again. If a number
here disagrees with the paper, this one is what the run said.
"""
import glob
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPERIMENTS = ROOT / "experiments"

POLICY_COLUMNS = [
    ("accuracy", "Accuracy", "{:.4f}"),
    ("tokens_per_question", "Tokens/q", "{:.1f}"),
    ("seconds_per_question", "Seconds/q", "{:.3f}"),
    ("median_batch_seconds", "Median s/batch", "{:.2f}"),
    ("escalation_rate", "Escalation", "{:.2%}"),
    ("tokens_vs_slow", "Tokens vs slow", "{:.1%}"),
    ("seconds_vs_slow", "Seconds vs slow", "{:.1%}"),
    ("accuracy_delta_vs_slow", "Acc − slow", "{:+.4f}"),
    ("gain_kept", "Gain kept", "{:.1%}"),
]


def policies_of(report):
    """Benchmarks written by different entry points name this block differently."""
    for key in ("summary", "policies"):
        if key in report:
            return report[key]
    return {}


def policy_table(report, title):
    rows = policies_of(report)
    if not rows:
        return ""
    present = [c for c in POLICY_COLUMNS if any(r.get(c[0]) is not None for r in rows.values())]
    out = [f"### {title}", "", "| Policy | " + " | ".join(h for _, h, _ in present) + " |",
           "| --- " * (len(present) + 1) + "|"]
    for name, row in rows.items():
        cells = []
        for key, _, fmt in present:
            value = row.get(key)
            cells.append("—" if value is None else fmt.format(value))
        out.append(f"| `{name}` | " + " | ".join(cells) + " |")
    questions = next(iter(rows.values())).get("questions")
    if questions:
        out += ["", f"{questions} questions."]
    return "\n".join(out) + "\n"


def seed_table(path, title, note=""):
    with open(path) as handle:
        payload = json.load(handle)
    columns, variants = payload["columns"], payload["variants"]
    seeds = len(next(iter(variants.values())))
    out = [f"### {title}", "", f"{seeds} seeds. Mean ± sample standard deviation.", ""]
    if note:
        out += [note, ""]
    out += ["| Variant | " + " | ".join(columns) + " |", "| --- " * (len(columns) + 1) + "|"]
    arrays = {k: list(zip(*v)) for k, v in variants.items()}
    for name, cols in arrays.items():
        cells = []
        for values in cols:
            mean = sum(values) / len(values)
            var = sum((v - mean) ** 2 for v in values) / (len(values) - 1) if len(values) > 1 else 0
            cells.append(f"{mean:.4f} ± {math.sqrt(var):.4f}")
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def one(pattern, folder):
    matches = sorted(glob.glob(str(EXPERIMENTS / folder / "results" / pattern)))
    return matches[-1] if matches else None


def mmlu_pro():
    parts = ["# MMLU-Pro, full results", "",
             "Generated by `scripts/report.py` from `results/`. Every measured column is here,",
             "including the ones the paper's table leaves out.", ""]
    for tag, title in (("table1-ce-unweighted-*.json", "Qwen3.5-4B, unweighted cross-entropy head"),
                       ("table1-27b-ce-*.json", "Qwen3.8-27B, unweighted cross-entropy head")):
        path = one(tag, "mmlu-pro")
        if path:
            with open(path) as handle:
                report = json.load(handle)
            parts.append(policy_table(report, title))
            parts.append(f"Source: `{Path(path).name}`, head "
                         f"`{report.get('decision_head', '?')}`, batch size "
                         f"{report.get('batch_size', '?')}.\n")
    path = one("table3-*.json", "mmlu-pro")
    if path:
        parts.append(seed_table(
            path, "Training objective, paper protocol",
            "The feature set is reselected per seed by grouped cross-validation, so the\n"
            "spread includes selection, not only initialisation. `gain_ece` is the binned\n"
            "gap between the predicted gain and the accuracy difference the two modes\n"
            "actually achieved; `ece` is the same quantity for the reported confidence."))
    path = one("repair-*.json", "mmlu-pro")
    if path:
        parts.append(seed_table(
            path, "CDPO's terms over an unweighted cross-entropy base",
            "Full unweighted cross-entropy underneath, the policy term added on top at a\n"
            "range of weights. Weight zero is the baseline."))
    for tag, name in (("head-4b-unweighted-report.json", "Qwen3.5-4B"),
                      ("head-27b-unweighted-report.json", "Qwen3.8-27B")):
        path = one(tag, "mmlu-pro")
        if not path:
            continue
        with open(path) as handle:
            report = json.load(handle)
        parts += [f"### Head selection, {name}", "",
                  f"Chosen: `{report['chosen']}`, layers {report['chosen_layers']}.", "",
                  "| Candidate | Validation routing AUROC | Held-out routing AUROC |",
                  "| --- | --- | --- |"]
        for row in report.get("sweep", []):
            val = row["validation"].get("auroc_gain_vs_helps")
            parts.append(f"| `{row['name']}` | "
                         + ("—" if val is None else f"{val:.4f}") + " | "
                         + f"{row['test']['auroc_gain_vs_helps']:.4f} |")
        parts.append("")
    return "\n".join(parts)


def simple(folder, title, tags):
    parts = [f"# {title}, full results", "",
             "Generated by `scripts/report.py` from `results/`.", ""]
    for tag, heading in tags:
        path = one(tag, folder)
        if not path:
            continue
        with open(path) as handle:
            report = json.load(handle)
        parts.append(policy_table(report, heading))
        extra = []
        if "dataset" in report and isinstance(report["dataset"], dict):
            d = report["dataset"]
            extra.append(f"source `{d.get('source')}`, revision `{d.get('revision')}`, "
                         f"split `{d.get('split')}`")
        if report.get("decision_head"):
            extra.append(f"head `{report['decision_head']}`")
        parts.append(f"Source: `{Path(path).name}`"
                     + ("; " + "; ".join(extra) if extra else "") + ".\n")
        if "by_type" in report:
            kinds = sorted({k for v in report["by_type"].values() for k in v})
            parts += ["### By question type", "",
                      "| Policy | " + " | ".join(kinds) + " |", "| --- " * (len(kinds) + 1) + "|"]
            for policy, counts in report["by_type"].items():
                cells = []
                for kind in kinds:
                    hit, total = counts.get(kind, (0, 0))
                    cells.append(f"{hit}/{total}" if total else "—")
                parts.append(f"| `{policy}` | " + " | ".join(cells) + " |")
            parts.append("")
    return "\n".join(parts)


def alfworld():
    fast, slow, meta = {}, {}, {}
    for path in glob.glob(str(EXPERIMENTS / "alfworld" / "results" / "alfworld-*.json")):
        with open(path) as handle:
            report = json.load(handle)
        if report.get("max_steps") != 50:      # the 30-step probe is superseded
            continue
        target = fast if report["mode"] == "fast" else slow
        for episode in report["episodes"]:
            target[episode["game"]] = episode
        meta[report["mode"]] = report
    if not (fast and slow):
        return "# ALFWorld, full results\n\nNo 50-step run present yet.\n"
    shared = sorted(set(fast) & set(slow))
    cells = {(a, b): 0 for a in (True, False) for b in (True, False)}
    for game in shared:
        cells[(fast[game]["success"], slow[game]["success"])] += 1
    n = len(shared)
    tokens = sum(slow[g]["generated"] for g in shared) / n
    steps_fast = sum(fast[g]["steps"] for g in shared) / n
    steps_slow = sum(slow[g]["steps"] for g in shared) / n
    oracle = (cells[(True, True)] + cells[(False, True)] + cells[(True, False)]) / n
    return "\n".join([
        "# ALFWorld, full results", "",
        "Generated by `scripts/report.py` from `results/`. "
        f"{n} `valid_unseen` episodes, 50-step limit, Qwen3.8-27B.", "",
        "### Endpoints", "",
        "| Policy | Success | Episodes | Mean steps | Generated tokens/episode |",
        "| --- | --- | --- | --- | --- |",
        f"| Fast only | {sum(1 for g in shared if fast[g]['success']) / n:.4f} | {n} | "
        f"{steps_fast:.1f} | 0 |",
        f"| Slow only | {sum(1 for g in shared if slow[g]['success']) / n:.4f} | {n} | "
        f"{steps_slow:.1f} | {tokens:.0f} |",
        f"| Oracle, per episode | {oracle:.4f} | {n} | — | — |", "",
        "Always thinking is worse than never thinking here, and pays eight thousand",
        "tokens an episode to be worse.", "",
        "The oracle chooses one mode per episode, knowing both outcomes in advance.",
        "It bounds that class of policy and nothing wider. A router deciding at every",
        "step produces trajectories that are neither all-fast nor all-slow, so it can",
        "in principle clear this line by escaping an episode both pure policies lose,",
        "and can equally fall below it by wandering into states neither pure policy",
        "visited. On MMLU-Pro the oracle really is a ceiling, because one question is",
        "one decision.", "",
        "### Where the two modes disagree", "",
        "| | Slow succeeds | Slow fails |",
        "| --- | --- | --- |",
        f"| **Fast succeeds** | {cells[(True, True)]} | {cells[(True, False)]} "
        f"({cells[(True, False)] / n:.1%}, thinking spoils) |",
        f"| **Fast fails** | {cells[(False, True)]} ({cells[(False, True)] / n:.1%}, "
        f"thinking rescues) | {cells[(False, False)]} |", "",
        f"The modes disagree on {cells[(True, False)] + cells[(False, True)]} of {n} episodes, "
        f"{(cells[(True, False)] + cells[(False, True)]) / n:.0%} of the benchmark. Spoils",
        "outnumber rescues, so a router keyed on how unsure the fast mode looks walks",
        "into the one as often as away from the other; what separates them is the gain.", "",
    ])


def main():
    written = {
        "mmlu-pro": mmlu_pro(),
        "alfworld": alfworld(),
        # Newest first, and one glob per run rather than one per benchmark: a
        # pattern loose enough to catch the next run is loose enough to caption
        # it with the last run's description.
        "agieval": simple("agieval", "AGIEval",
                          [("bench-agieval-sglang-*.json",
                            "Qwen3.8-27B, unweighted cross-entropy head"),
                           ("bench-agieval-b10-*.json",
                            "Qwen3.5-4B, superseded class-weighted head")]),
        "gpqa-diamond": simple("gpqa-diamond", "GPQA-Diamond",
                               [("bench-gpqa-diamond-sglang-*.json",
                                 "Qwen3.8-27B, unweighted cross-entropy head"),
                                ("bench-gpqa-b10-*.json",
                                 "Qwen3.5-4B, MMLU-Pro head, nothing retrained")]),
        "self-constructed": simple("self-constructed", "Self-constructed typed requests",
                                   [("constructed-*.json", "Qwen3.5-4B, unweighted cross-entropy head")]),
    }
    for folder, text in written.items():
        path = EXPERIMENTS / folder / "results.md"
        path.write_text(text.rstrip() + "\n")
        print(f"{path.relative_to(ROOT)}  {len(text.splitlines())} lines")


if __name__ == "__main__":
    main()
